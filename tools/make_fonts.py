# LVGL's built-in icons (LV_SYMBOL_*), from its own font generator.
SYMBOLS = [
    int(c)
    for c in (
        '61441,61448,61451,61452,61453,61457,61459,61461,61465,61468,61473,61478,61479,61480,61502,'
        '61507,61512,61515,61516,61517,61521,61522,61523,61524,61543,61544,61550,61552,61553,61556,'
        '61559,61560,61561,61563,61587,61589,61636,61637,61639,61641,61664,61671,61674,61683,61724,'
        '61732,61787,61931,62016,62017,62018,62019,62020,62087,62099,62212,62189,62810,63426,63650'
    ).split(',')
]


def ranges(rs):
    return ','.join(f'0x{a:X}' if a == b else f'0x{a:X}-0x{b:X}' for a, b in rs)


npx = 'npx.cmd' if os.name == 'nt' else 'npx'
for size in (12, 16, 24):
    out = os.path.join(ROOT, 'src', 'fonts', f'perch_font_{size}.c')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    cmd = [
        npx,
        '--yes',
        'lv_font_conv',
        '--no-compress',
        '--no-prefilter',
        '--bpp',
        '4',
        '--size',
        str(size),
        '--format',
        'lvgl',
        '--force-fast-kern-format',
        '--lv-include',
        'lvgl.h',
        '--lv-font-name',
        f'perch_font_{size}',
        '-o',
        out,
        '--font',
        os.path.join(SRC, 'Montserrat-Medium.ttf'),
        '-r',
        ranges(LATIN),
        '--font',
        os.path.join(SRC, 'DejaVuSans.ttf'),
        '-r',
        ranges(MATH),
        '--font',
        os.path.join(SRC, 'FontAwesome5-Solid+Brands+Regular.woff'),
        '-r',
        ','.join(map(str, SYMBOLS)),
    ]
    subprocess.run(cmd, check=True)
    print('wrote', os.path.relpath(out, ROOT))

codes = sorted({c for a, b in LATIN + MATH for c in range(a, b + 1)} | set(SYMBOLS))
with open(os.path.join(ROOT, 'include', 'glyphs.h'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by tools/make_fonts.py: every character the display fonts can draw.\n')
    f.write('#pragma once\n#include <stdint.h>\n\n')
    f.write(f'static const uint16_t DISPLAY_GLYPHS[{len(codes)}] = {{\n')
    for i in range(0, len(codes), 12):
        f.write('  ' + ', '.join(f'0x{c:04X}' for c in codes[i : i + 12]) + ',\n')
    f.write('};\n\n')
    f.write('inline bool displayHasGlyph(uint32_t code) {\n')
    f.write('  if (code >= 0x20 && code < 0x7F) return true;\n')
    f.write('  int lo = 0, hi = sizeof DISPLAY_GLYPHS / sizeof DISPLAY_GLYPHS[0] - 1;\n')
    f.write('  while (lo <= hi) {\n    const int mid = (lo + hi) / 2;\n')
    f.write('    if (DISPLAY_GLYPHS[mid] == code) return true;\n')
    f.write('    if (DISPLAY_GLYPHS[mid] < code) lo = mid + 1; else hi = mid - 1;\n  }\n  return false;\n}\n')
print(len(codes), 'glyphs')
