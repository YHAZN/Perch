"""Build the display fonts: Montserrat (Latin) + DejaVu Sans (math, Greek, super/subscripts)
+ LVGL's symbol icons, at 12, 16 and 24 px. Also writes include/glyphs.h, the sorted list of
every character the fonts can draw, so the firmware knows what it may show.

Needs Node (npx downloads LVGL's lv_font_conv) and the font files from the LVGL library
(.pio/libdeps/<env>/lvgl/scripts/built_in_font). Run from the project root:
    python tools/make_fonts.py
"""

import glob
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sorted(glob.glob(os.path.join(ROOT, '.pio', 'libdeps', '*', 'lvgl', 'scripts', 'built_in_font')))
if not SRC:
    sys.exit('LVGL font sources not found: build once so PlatformIO fetches LVGL.')
SRC = SRC[0]

# Montserrat: printable ASCII and Latin-1 (accents, ½ ± × ÷ ² ³ · °).
